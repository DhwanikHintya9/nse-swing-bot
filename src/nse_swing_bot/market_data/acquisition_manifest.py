"""Deterministic, immutable manifests for read-only market-data acquisition."""

from __future__ import annotations

import hashlib
import hmac
import json
import os
import tempfile
from collections.abc import Mapping
from pathlib import Path
from typing import Any

_REQUIRED_FIELDS = {
    "schema_version",
    "manifest_id",
    "run_started_at_utc",
    "run_completed_at_utc",
    "provider",
    "read_only",
    "orders_endpoint_calls",
    "production_eligible",
    "adjustment_status",
    "symbols",
}
_FORBIDDEN_KEY_PARTS = (
    "api_key",
    "access_token",
    "api_secret",
    "password",
    "authorization",
    "client_secret",
)


class AcquisitionManifestError(ValueError):
    """Raised when an acquisition manifest is incomplete or fails integrity checks."""


def _canonical_json_bytes(payload: Mapping[str, Any]) -> bytes:
    try:
        return json.dumps(
            payload,
            ensure_ascii=False,
            allow_nan=False,
            sort_keys=True,
            separators=(",", ":"),
        ).encode("utf-8")
    except (TypeError, ValueError) as error:
        raise AcquisitionManifestError(f"manifest is not canonical JSON data: {error}") from error


def _reject_credential_fields(value: Any, path: str = "manifest") -> None:
    if isinstance(value, Mapping):
        for key, child in value.items():
            normalized = str(key).strip().lower().replace("-", "_")
            if any(part in normalized for part in _FORBIDDEN_KEY_PARTS):
                raise AcquisitionManifestError(
                    f"credential-like field is not permitted in manifest: {path}.{key}"
                )
            _reject_credential_fields(child, f"{path}.{key}")
    elif isinstance(value, list):
        for index, child in enumerate(value):
            _reject_credential_fields(child, f"{path}[{index}]")


def build_acquisition_manifest(payload: Mapping[str, Any]) -> dict[str, Any]:
    """Validate the run envelope and attach a SHA-256 over canonical payload JSON."""
    if not isinstance(payload, Mapping):
        raise AcquisitionManifestError("manifest payload must be a mapping")
    missing = _REQUIRED_FIELDS.difference(payload)
    if missing:
        raise AcquisitionManifestError(
            "manifest is missing required fields: " + ", ".join(sorted(missing))
        )
    if "manifest_sha256" in payload:
        raise AcquisitionManifestError("manifest_sha256 is generated by the manifest builder")
    if payload["schema_version"] != 1:
        raise AcquisitionManifestError("unsupported acquisition manifest schema_version")
    if not isinstance(payload["manifest_id"], str) or not payload["manifest_id"].strip():
        raise AcquisitionManifestError("manifest_id must be a non-empty string")
    if payload["read_only"] is not True:
        raise AcquisitionManifestError("acquisition manifest must declare read_only=true")
    if payload["orders_endpoint_calls"] != 0:
        raise AcquisitionManifestError("acquisition manifest must record zero order endpoint calls")
    if payload["production_eligible"] is not False:
        raise AcquisitionManifestError("acquisition artifacts must not be production eligible")
    if payload["adjustment_status"] != "provider_adjusted_unreconciled":
        raise AcquisitionManifestError(
            "Kite candles must declare adjustment_status=provider_adjusted_unreconciled"
        )
    if not isinstance(payload["symbols"], list):
        raise AcquisitionManifestError("symbols must be a list")
    _reject_credential_fields(payload)
    normalized = json.loads(_canonical_json_bytes(payload).decode("utf-8"))
    digest = hashlib.sha256(_canonical_json_bytes(normalized)).hexdigest()
    return {**normalized, "manifest_sha256": digest}


def verify_acquisition_manifest(manifest: Mapping[str, Any]) -> bool:
    """Verify the canonical payload digest; raise on malformed or tampered input."""
    if not isinstance(manifest, Mapping) or "manifest_sha256" not in manifest:
        raise AcquisitionManifestError("manifest_sha256 is missing")
    supplied_digest = manifest["manifest_sha256"]
    if not isinstance(supplied_digest, str) or len(supplied_digest) != 64:
        raise AcquisitionManifestError("manifest_sha256 must be a 64-character hex digest")
    payload = {key: value for key, value in manifest.items() if key != "manifest_sha256"}
    rebuilt = build_acquisition_manifest(payload)
    if not hmac.compare_digest(rebuilt["manifest_sha256"], supplied_digest):
        raise AcquisitionManifestError("manifest SHA-256 does not match canonical payload")
    return True


def write_acquisition_manifest(
    manifest: Mapping[str, Any], destination: Path
) -> Path:
    """Atomically create a manifest without ever replacing an existing artifact."""
    verify_acquisition_manifest(manifest)
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    data = _canonical_json_bytes(manifest) + b"\n"
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=".acquisition-manifest-", dir=destination.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        # A hard link publishes the fully written file atomically and fails if
        # destination already exists; os.replace would silently overwrite it.
        os.link(temporary, destination)
        temporary.unlink()
    except FileExistsError as error:
        temporary.unlink(missing_ok=True)
        raise FileExistsError(
            f"refusing to overwrite acquisition manifest: {destination}"
        ) from error
    except Exception:
        temporary.unlink(missing_ok=True)
        raise
    return destination


def sha256_file(path: Path) -> str:
    """Return the SHA-256 digest of a file without loading it all into memory."""
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()
